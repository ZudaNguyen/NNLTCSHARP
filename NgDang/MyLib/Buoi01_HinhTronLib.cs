namespace MyLib
{
    public class HinhTronLib
    {
        // Chỉ chứa logic tính toán, trả về kết quả
        public double TinhDienTich(double r)
        {
            return 3.14 * r * r;
        }

        public double TinhChuVi(double r)
        {
            return 2 * 3.14 * r;
        }
    }
